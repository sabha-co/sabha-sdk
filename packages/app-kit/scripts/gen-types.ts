// Regenerates src/generated/api.ts from Sabha's OpenAPI spec.
// With no argument it reads the vendored spec/v1.yaml; pass a path (such as
// ../sabha-ai/config/openapi/v1.yaml) to refresh the vendored copy first.
import { copyFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const vendored = fileURLToPath(new URL("../spec/v1.yaml", import.meta.url));
const output = fileURLToPath(new URL("../src/generated/api.ts", import.meta.url));

const source = process.argv[2];
if (source) copyFileSync(source, vendored);

const ast = await openapiTS(new URL(`file://${vendored}`), { alphabetize: true });
const banner = "// Generated by scripts/gen-types.ts from spec/v1.yaml. Do not edit by hand.\n\n";
writeFileSync(output, banner + astToString(ast));
console.log(`wrote ${output}`);
